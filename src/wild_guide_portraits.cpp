bool guidePortraitBitmap(Portrait portrait, const uint8_t*& output,
                         size_t& outputBytes) {
  output = nullptr;
  outputBytes = 0U;
  for (size_t index = 0U; index < kCatalogCreatureCount; ++index) {
    if (kGuidePortraitOrder[index] != portrait) continue;
    output = kGuidePortraits[index];
    outputBytes = kGuidePortraitBytes;
    return true;
  }
  return false;
}

