size_t creatureCount() { return sizeof(kCreatures) / sizeof(kCreatures[0]); }

bool creatureAt(size_t index, Creature& output) {
  if (index >= creatureCount()) return false;
  output = kCreatures[index];
  return true;
}

bool creatureByPackId(uint32_t packId, Creature& output) {
  for (const Creature& creature : kCreatures) {
    if (creature.packId == packId) {
      output = creature;
      return true;
    }
  }
  return false;
}

bool creatureForRarity(signal::Rarity rarity, uint32_t selectionEntropy,
                       Creature& output) {
  if (!signal::validRarity(rarity)) return false;
  size_t candidates = 0U;
  for (const Creature& creature : kCreatures) {
    if (creature.rarity == rarity) ++candidates;
  }
  if (candidates == 0U) return false;
  size_t selected = static_cast<size_t>(selectionEntropy % candidates);
  for (const Creature& creature : kCreatures) {
    if (creature.rarity != rarity) continue;
    if (selected-- == 0U) {
      output = creature;
      return true;
    }
  }
  return false;
}

bool portraitBitmap(Portrait portrait, const uint8_t*& output,
                    size_t& outputBytes) {
  output = nullptr;
  outputBytes = 0U;
  switch (portrait) {
    case Portrait::Frog: output = kFrogPortrait; break;
    case Portrait::Rabbit: output = kRabbitPortrait; break;
    case Portrait::Otter: output = kOtterPortrait; break;
    case Portrait::Raccoon: output = kRaccoonPortrait; break;
    case Portrait::RedPanda: output = kRedPandaPortrait; break;
    case Portrait::SnowLeopard: output = kSnowLeopardPortrait; break;
    case Portrait::CatGirl: output = kCatGirlPortrait; break;
    default: return false;
  }
  outputBytes = kPortraitBytes;
  return true;
}

